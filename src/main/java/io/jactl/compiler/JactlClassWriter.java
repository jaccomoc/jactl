package io.jactl.compiler;

import io.jactl.JactlContext;
import io.jactl.Utils;
import org.objectweb.asm.ClassVisitor;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.Type;
import org.objectweb.asm.util.CheckClassAdapter;
import org.objectweb.asm.util.Printer;
import org.objectweb.asm.util.Textifier;
import org.objectweb.asm.util.TraceClassVisitor;

import java.io.PrintWriter;

import static org.objectweb.asm.Opcodes.ASM8;

public class JactlClassWriter extends ClassWriter {

  JactlContext context;
  String       internalJavaPackage;
  ClassVisitor cv;
  String       className;
  String       superName;
  
  public JactlClassWriter(JactlContext context, String className, String superName) {
    super(COMPUTE_MAXS + COMPUTE_FRAMES);
    this.context = context;
    this.internalJavaPackage = context.internalJavaPackage;
    init(context.debugLevel, className, superName);
  }
  
  public JactlClassWriter(String internalJavaPackage, String className, String superName) {
    this(internalJavaPackage, 0, className, superName);
  }
  
  public JactlClassWriter(String internalJavaPackage, int debugLevel, String className, String superName) {
    super(COMPUTE_MAXS + COMPUTE_FRAMES);
    this.internalJavaPackage = internalJavaPackage;
    init(debugLevel, className, superName);
  }
  
  private void init(int debugLevel, String className, String superName) {
    cv = this;
    this.className = className;
    this.superName = superName;
    if (debugLevel > 0 || context != null && context.checkClasses()) {
      cv = new CheckClassAdapter(cv);
    }
    if (debugLevel > 0) {
      Printer printer = new JactlTextifier();
      cv = new TraceClassVisitor(cv, printer, new PrintWriter(System.out) {
        { super.print(": "); }
        @Override
        public void print(String s) {
          super.print(s.replaceAll("\n", "\n: "));
        }
      });
    }
  }
  
  public ClassVisitor getClassVisitor() {
    return cv == null ? this : cv;
  }

  private static final String objectClass = Utils.OBJECT_INTERNAL;

  @Override
  protected String getCommonSuperClass(String type1, String type2) {
    if (type1.equals(type2)) {
      return type1;
    }
    if (type1.equals(objectClass) || type2.equals(objectClass)) {
      return objectClass;
    }
    if (type1.equals(className)) {
      return getCommonSuperClass(superName, type2);
    }
    if (type2.equals(className)) {
      return getCommonSuperClass(type1, superName);
    }
    String jactlObjectClass = Utils.JACTL_OBJECT_INTERNAL;
    boolean type1StartsWithJavaPackage = type1.startsWith(internalJavaPackage);
    if (type1StartsWithJavaPackage && type2.equals(jactlObjectClass)) {
      return jactlObjectClass;
    }
    boolean type2StartsWithJavaPackage = type2.startsWith(internalJavaPackage);
    if (type2StartsWithJavaPackage && type1.equals(jactlObjectClass)) {
      return jactlObjectClass;
    }
    try {
      if (type1StartsWithJavaPackage && type2StartsWithJavaPackage) {
        Class clss1 = context.getClass(type1);
        if (clss1 == null) {
          throw new IllegalStateException("Internal error: Cannot find class " + type1);
        }
        Class clss2 = context.getClass(type2);
        if (clss2 == null) {
          throw new IllegalStateException("Internal error: Cannot find class " + type2);
        }
        if (clss1.isAssignableFrom(clss2)) {
          return type1;
        }
        if (clss2.isAssignableFrom(clss1)) {
          return type2;
        }
        if (clss1.isInterface() || clss2.isInterface()) {
          return jactlObjectClass;
        }
        else {
          do {
            clss1 = clss1.getSuperclass();
          }
          while (clss1 != null && !clss1.isAssignableFrom(clss2));
          
          return clss1 == null ? jactlObjectClass : Type.getInternalName(clss1);
        }
      }
      else if (type1StartsWithJavaPackage || type2StartsWithJavaPackage) {
        // Common ancestor of Jactl class and non-Jactl class is Object, but I am not sure
        // if returning Object is the right answer or whether this is just hiding an issue
        // in the generated bytecode...
        return Utils.OBJECT_INTERNAL;
      }
      return super.getCommonSuperClass(type1, type2);
    }
    catch (IllegalStateException e) {
      throw e;
    }
    catch (Exception e) {
      throw new IllegalStateException(e);
    }
  }

  /**
   * Textifier that truncates long strings when outputing LDC instructions
   */
  private static class JactlTextifier extends Textifier {
    JactlTextifier() { super(ASM8); }
    @Override public void visitLdcInsn(Object v) {
      super.visitLdcInsn(v instanceof String && ((String) v).length() > 80 ? ((String) v).substring(0, 80) + " ..." : v);
    }
    @Override public Textifier visitMethod(int access, String name, String descriptor, String signature, String[] exceptions) {
      super.visitMethod(access, name, descriptor, signature, exceptions);
      Textifier textifier = new JactlTextifier();
      text.add(textifier.getText());
      return textifier;
    }
  }
}
